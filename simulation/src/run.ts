import fs from "node:fs";
import path from "node:path";
import { renderSvg } from "./chart";
import { DEFAULT_CONFIG, simulate, STRATEGIES, type Config, type Strategy } from "./model";

const SEEDS = Number(process.env.SEEDS) || 50;
const LIMIT = Number(process.env.LIMIT) || DEFAULT_CONFIG.limit;
const TAIL_DAYS = 30; // compare on the last 30 days, after all cards have been added

const LABEL: Record<Strategy, string> = {
  random: "Random revisiting",
  sm2: "SM-2, most overdue first",
  pattern: "Pattern-weighted queue",
};
const COLOR: Record<Strategy, string> = { random: "#868e96", sm2: "#e67700", pattern: "#3b5bdb" };

const scenarios = [
  { key: "transfer", title: "Pattern-level transfer (assumed)", transfer: 0.8 },
  { key: "no-transfer", title: "No transfer between problems", transfer: 0 },
];

const mean = (xs: number[]) => xs.reduce((a, b) => a + b, 0) / xs.length;
function stderr(xs: number[]): number {
  if (xs.length < 2) return 0;
  const m = mean(xs);
  const variance = xs.reduce((s, x) => s + (x - m) ** 2, 0) / (xs.length - 1);
  return Math.sqrt(variance / xs.length);
}
const pct = (x: number) => `${(x * 100).toFixed(1)}%`;
const pp = (x: number) => `${(x * 100).toFixed(2)}`;

const docsDir = path.resolve(__dirname, "..", "..", "docs");
const shotsDir = path.join(docsDir, "screenshots");
const resultsDir = path.resolve(__dirname, "..", "results");
fs.mkdirSync(shotsDir, { recursive: true });
fs.mkdirSync(resultsDir, { recursive: true });

const md: string[] = [
  "# Simulation results",
  "",
  "_Generated by `simulation/src/run.ts`. Do not edit by hand; run `npm run sim` in `simulation/`._",
  "",
  `Settings: ${DEFAULT_CONFIG.days} days, ${DEFAULT_CONFIG.patterns} patterns x ${DEFAULT_CONFIG.perPattern} problems, ` +
    `${DEFAULT_CONFIG.newPerDay} new problems per day, ${LIMIT} reviews per day, ${SEEDS} random seeds.`,
  `Metric: average recall probability across all problems, on days ${DEFAULT_CONFIG.days - TAIL_DAYS} to ${DEFAULT_CONFIG.days - 1}. ` +
    "Values are mean +/- standard error across seeds.",
  "",
];
const summary: Record<string, unknown> = { seeds: SEEDS, limit: LIMIT };

for (const sc of scenarios) {
  const config: Config = { ...DEFAULT_CONFIG, limit: LIMIT, transfer: sc.transfer };
  const runs: Record<Strategy, number[][]> = { random: [], sm2: [], pattern: [] };
  for (let seed = 1; seed <= SEEDS; seed++) {
    for (const s of STRATEGIES) runs[s].push(simulate(config, seed, s));
  }

  const tail = {} as Record<Strategy, number[]>;
  const last = {} as Record<Strategy, number[]>;
  const curves = {} as Record<Strategy, number[]>;
  for (const s of STRATEGIES) {
    tail[s] = runs[s].map((r) => mean(r.slice(-TAIL_DAYS)));
    last[s] = runs[s].map((r) => r[r.length - 1]);
    curves[s] = Array.from({ length: config.days }, (_, d) => mean(runs[s].map((r) => r[d])));
  }

  const diffs = tail.pattern.map((v, i) => v - tail.sm2[i]);
  const wins = diffs.filter((d) => d > 0).length;

  // console output
  console.log(`\n=== ${sc.title} (transfer = ${sc.transfer}) ===`);
  for (const s of STRATEGIES) {
    console.log(`${LABEL[s].padEnd(28)} last-30-day mean ${pct(mean(tail[s]))} +/- ${pct(stderr(tail[s]))}   final day ${pct(mean(last[s]))}`);
  }
  console.log(`pattern minus SM-2: ${pp(mean(diffs))} points (SE ${pp(stderr(diffs))}), ahead in ${wins}/${SEEDS} seeds`);

  // chart
  const svg = renderSvg(
    `Retention over ${config.days} days: ${sc.title}`,
    `${LIMIT} reviews per day, mean of ${SEEDS} simulated learners. Assumption-based simulation, not real user data.`,
    STRATEGIES.map((s) => ({ name: LABEL[s], color: COLOR[s], values: curves[s] }))
  );
  fs.writeFileSync(path.join(shotsDir, `simulation-${sc.key}.svg`), svg);

  // markdown
  md.push(`## Scenario: ${sc.title} (transfer = ${sc.transfer})`, "");
  md.push(`![${sc.title}](screenshots/simulation-${sc.key}.svg)`, "");
  md.push("| Strategy | Mean recall, last 30 days | Recall on final day |", "|---|---|---|");
  for (const s of STRATEGIES) {
    md.push(`| ${LABEL[s]} | ${pct(mean(tail[s]))} +/- ${pct(stderr(tail[s]))} | ${pct(mean(last[s]))} |`);
  }
  md.push(
    "",
    `Pattern-weighted minus SM-2: **${pp(mean(diffs))} percentage points** (standard error ${pp(stderr(diffs))}); ` +
      `pattern-weighted was ahead in **${wins} of ${SEEDS}** seeds.`,
    ""
  );

  summary[sc.key] = {
    transfer: sc.transfer,
    lastThirtyDayMean: Object.fromEntries(STRATEGIES.map((s) => [s, mean(tail[s])])),
    pairedDiffPatternMinusSm2: { mean: mean(diffs), stderr: stderr(diffs), wins, seeds: SEEDS },
  };
}

fs.writeFileSync(path.join(docsDir, "simulation-results.md"), md.join("\n") + "\n");
fs.writeFileSync(path.join(resultsDir, "summary.json"), JSON.stringify(summary, null, 2) + "\n");
console.log("\nWrote docs/simulation-results.md, docs/screenshots/simulation-*.svg and simulation/results/summary.json");
